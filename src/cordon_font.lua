local CACHE = {}
for char, paths in pairs(GRID) do
    local strokes = {}
    for _, path in ipairs(paths) do
        for i = 1, #path - 2, 2 do
            local stroke = {
                x0 = path[i] * 0.15, y0 = 1 - path[i + 1] / 6,
                x1 = path[i + 2] * 0.15, y1 = 1 - path[i + 3] / 6,
            }
            strokes[#strokes + 1] = stroke
        end
    end
    CACHE[char] = strokes
end

function F.get(char)
    if type(char) ~= 'string' or #char ~= 1 then return nil end
    return CACHE[string.upper(char)]
end

return F
